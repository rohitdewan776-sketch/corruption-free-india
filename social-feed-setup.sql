create extension if not exists pgcrypto;

create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique check (char_length(username) between 2 and 32),
  created_at timestamptz not null default now()
);

create or replace function public.create_profile_for_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  base_name text;
begin
  base_name := lower(regexp_replace(
    coalesce(new.raw_user_meta_data ->> 'username', split_part(coalesce(new.email, 'citizen'), '@', 1)),
    '[^a-zA-Z0-9_]+', '', 'g'
  ));
  base_name := left(coalesce(nullif(base_name, ''), 'citizen'), 23) || '_' || left(new.id::text, 8);
  insert into public.profiles (user_id, username)
  values (new.id, base_name)
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists create_profile_after_signup on auth.users;
create trigger create_profile_after_signup
after insert on auth.users
for each row execute procedure public.create_profile_for_user();

create table if not exists public.videos (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 120),
  state text not null check (char_length(state) between 1 and 60),
  city text check (city is null or char_length(city) <= 60),
  description text check (description is null or char_length(description) <= 500),
  video_url text not null check (
    char_length(video_url) <= 2048 and (
      video_url ~* '^https://(www\.)?(youtube\.com|youtube-nocookie\.com|youtu\.be|vimeo\.com|player\.vimeo\.com|dailymotion\.com|dai\.ly)/'
      or video_url like 'https://luzjxwwjhxysxwhkzydd.supabase.co/storage/v1/object/public/citizen-videos/%'
    )
  ),
  created_at timestamptz not null default now()
);

