create policy "Public videos are readable"
on public.videos for select to anon, authenticated using (true);
create policy "Authenticated creators publish videos"
on public.videos for insert to authenticated
with check (
  user_id = (select auth.uid())
  and char_length(title) between 1 and 120
  and char_length(state) between 1 and 60
  and (city is null or char_length(city) <= 60)
  and (description is null or char_length(description) <= 500)
);
create policy "Creators update their videos"
on public.videos for update to authenticated
using (user_id = (select auth.uid()))
with check (user_id = (select auth.uid()));
create policy "Creators delete their videos"
on public.videos for delete to authenticated
using (user_id = (select auth.uid()));

